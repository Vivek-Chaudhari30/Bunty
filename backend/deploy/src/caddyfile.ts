// Builds the Caddyfile for one server: the router plus one HTTPS subdomain per assistant
// (infra/README.md "Server"). Input is infra/assistants.json, which lists ids and the local
// port of each assistant's gateway (from `vellum ps`). No secrets in either file.

export interface AssistantEntry {
  id: string;
  /** Local port of the assistant's Vellum gateway on the server. */
  gatewayPort: number;
}

export interface DeployConfig {
  /** Base domain, e.g. "bunty.example.com". Router at router.<domain>, assistants at <id>.<domain>. */
  domain: string;
  /** Email for Let's Encrypt certificate notices. */
  acmeEmail: string;
  routerPort: number;
  assistants: AssistantEntry[];
}

const ID = /^[a-z0-9][a-z0-9-]{0,40}$/;
const DOMAIN = /^(?=.{3,253}$)([a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?\.)+[a-z]{2,}$/;

export function validate(c: DeployConfig): string[] {
  const errors: string[] = [];
  if (!DOMAIN.test(c.domain)) errors.push(`domain "${c.domain}" is not a domain name`);
  if (!/^[^@\s]+@[^@\s]+$/.test(c.acmeEmail)) errors.push("acmeEmail is not an email address");
  const seenIds = new Set<string>();
  const seenPorts = new Set<number>([c.routerPort]);
  for (const a of c.assistants) {
    if (!ID.test(a.id) || a.id === "router") errors.push(`assistant id "${a.id}" must be lowercase letters, digits, dashes (not "router")`);
    if (seenIds.has(a.id)) errors.push(`assistant id "${a.id}" is listed twice`);
    if (!Number.isInteger(a.gatewayPort) || a.gatewayPort < 1 || a.gatewayPort > 65535) errors.push(`assistant "${a.id}" has a bad port`);
    if (seenPorts.has(a.gatewayPort)) errors.push(`port ${a.gatewayPort} is used twice`);
    seenIds.add(a.id);
    seenPorts.add(a.gatewayPort);
  }
  return errors;
}

export function buildCaddyfile(c: DeployConfig): string {
  const errors = validate(c);
  if (errors.length) throw new Error(`infra/assistants.json: ${errors.join("; ")}`);
  const blocks = [
    `{\n\temail ${c.acmeEmail}\n}`,
    `router.${c.domain} {\n\treverse_proxy router:${c.routerPort}\n\tlog\n}`,
    ...c.assistants.map(
      (a) =>
        // Assistants run on the host (vellum hatch), so Caddy reaches them through the host gateway.
        `${a.id}.${c.domain} {\n\treverse_proxy host.docker.internal:${a.gatewayPort}\n\tlog\n}`,
    ),
  ];
  return `# Generated by backend/deploy/scripts/gen-caddyfile.ts from infra/assistants.json. Do not edit by hand.\n\n${blocks.join("\n\n")}\n`;
}

/** The URL to register for each assistant in the router (backend/router/scripts/add-user.ts). */
export function assistantBaseUrl(c: DeployConfig, id: string): string {
  return `https://${id}.${c.domain}`;
}
